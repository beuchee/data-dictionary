"""Resolution parity with the repo's resolve.py, and the SQL contract shared
with the web app (tests/fixtures/vocab/*.json, regenerated by make_expected.py)."""

import importlib.util

import duckdb
import pytest

from app.services import resolver
from app.services import vocabulary as lib

from vocab_fixtures import ATHENA_DIR, RESOLVE_CASES, SQL_GOLDEN, VOCAB_DIR, build_library, edges_connection

MAKE_EXPECTED = VOCAB_DIR / "make_expected.py"


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


expected_module = _load("make_expected", MAKE_EXPECTED)


@pytest.fixture(scope="module")
def resolve_py():
    return _load("resolve_py", expected_module.REPO / "resolve.py")


@pytest.fixture
def library_cursor():
    build_library()
    cursor = lib.get_library().cursor()
    yield cursor
    cursor.close()


CASE_IDS = [c["name"] for c in RESOLVE_CASES]


@pytest.mark.parametrize("case", RESOLVE_CASES, ids=CASE_IDS)
def test_resolve_py_still_gives_the_expected_output(case, resolve_py):
    con = resolve_py.connect_from_csv(str(ATHENA_DIR))
    try:
        assert resolve_py.resolve_concept_set(con, case["items"]) == case["resolvedConcepts"]
    finally:
        con.close()


@pytest.mark.parametrize("case", RESOLVE_CASES, ids=CASE_IDS)
def test_resolver_on_the_imported_library_matches_resolve_py(case, library_cursor):
    concepts = resolver.resolve_items(library_cursor, case["items"], "closure")
    assert concepts == case["resolvedConcepts"]
    version = resolver.stamp_version(resolver.read_vocabulary_version(library_cursor), concepts)
    assert version == case["vocabularyVersion"]


@pytest.mark.parametrize("case", RESOLVE_CASES, ids=CASE_IDS)
def test_resolver_on_direct_edges_only_matches_resolve_py(case):
    # The browser keeps only the direct concept_ancestor rows and walks them.
    con = edges_connection()
    try:
        assert resolver.resolve_items(con, case["items"], "edges") == case["resolvedConcepts"]
    finally:
        con.close()


def test_resolver_rejects_a_non_integer_concept_id(library_cursor):
    items = [{"concept": {"conceptId": "1) OR (1=1"}, "includeDescendants": True}]
    with pytest.raises(ValueError):
        resolver.resolve_items(library_cursor, items)


def test_version_is_none_without_a_vocabulary_table():
    con = duckdb.connect()
    assert resolver.read_vocabulary_version(con) is None
    assert resolver.stamp_version(None, [{"vocabularyId": "LOINC"}]) is None


# --- SQL contract -------------------------------------------------------------------------------


@pytest.mark.parametrize("case", SQL_GOLDEN["cases"], ids=lambda c: f"{c['builder']}-{c['input']}")
def test_builders_produce_the_golden_sql(case):
    assert expected_module.call(case["builder"], case["input"]) == case["output"]


@pytest.mark.parametrize("case", SQL_GOLDEN["rejects"], ids=lambda c: f"{c['builder']}-{c['input']}")
def test_builders_reject_unsafe_input(case):
    with pytest.raises((ValueError, TypeError)):
        expected_module.call(case["builder"], case["input"])


def _queries(output):
    return [output["page"], output["count"]] if "page" in output else [output]


def _run(con, query):
    # Sorted: DISTINCT without ORDER BY may come back in any order.
    return sorted(con.execute(query["sql"], query["params"]).fetchall(), key=repr)


@pytest.mark.parametrize("case", SQL_GOLDEN["cases"], ids=lambda c: f"{c['builder']}-{c['input']}")
def test_golden_sql_runs_on_both_ancestor_layouts(case, library_cursor):
    """Every query the browser sends runs here too, on the server's full closure
    and on the browser's direct edges; an `edges` query gives the same rows on
    both, and the same as its `closure` twin."""
    edges = edges_connection()
    try:
        for query in _queries(case["output"]):
            on_library = _run(library_cursor, query)
            on_edges = _run(edges, query)
            if case["input"].get("mode") != "closure":
                assert on_library == on_edges
            if case["input"].get("mode") == "edges":
                twin = expected_module.call(case["builder"], {**case["input"], "mode": "closure"})
                assert _run(library_cursor, twin) == on_edges
    finally:
        edges.close()
